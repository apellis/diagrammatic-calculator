// Generates src/engine/ops.gen.ts, the TypeScript types of every operation's request and response,
// from the JSON Schemas in spec/ops/. CI checks that the committed file is current.
import { compile } from 'json-schema-to-typescript';
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(import.meta.dirname, '../../spec/ops');
const out = path.join(import.meta.dirname, '../src/engine/ops.gen.ts');
const common = JSON.parse(fs.readFileSync(path.join(dir, 'common.schema.json'), 'utf8'));
const pascal = (s) => s.split(/[^a-zA-Z0-9]/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('');

// Refs into common.schema.json become local refs to a copy of its definitions.
function localize(v, prefix) {
  if (Array.isArray(v)) return v.map((x) => localize(x, prefix));
  if (v && typeof v === 'object') {
    const o = {};
    for (const [k, x] of Object.entries(v)) {
      if (k === '$ref' && typeof x === 'string') {
        o[k] = x.startsWith('common.schema.json#/$defs/')
          ? `#/$defs/${x.slice('common.schema.json#/$defs/'.length)}`
          : x.replace('#/$defs/', `#/$defs/${prefix}`);
      } else o[k] = localize(x, prefix);
    }
    return o;
  }
  return v;
}

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.schema.json') && f !== 'common.schema.json').sort();
const defs = {};
// 'error' would shadow the global Error type
const commonTitle = (k) => (k === 'error' ? 'OpError' : pascal(k));
for (const [k, v] of Object.entries(common.$defs)) defs[k] = { ...localize(v, ''), title: commonTitle(k) };
const ops = [];
for (const f of files) {
  const op = f.replace('.schema.json', '');
  const schema = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const prefix = pascal(op);
  for (const [k, v] of Object.entries(schema.$defs)) {
    defs[`${prefix}${pascal(k)}`] = { ...localize(v, prefix), title: `${prefix}${pascal(k)}` };
  }
  ops.push([op, prefix]);
}
const root = {
  title: 'Operations',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  $defs: defs,
};
// localize() prefixed op-local refs with the op's name; make the rest of the key match defs
let text = JSON.stringify(root);
for (const [, prefix] of ops) {
  text = text.replace(new RegExp(`"#/\\$defs/${prefix}([a-zA-Z]+)"`, 'g'), (_, k) => `"#/$defs/${prefix}${pascal(k)}"`);
}
let ts = await compile(JSON.parse(text), 'Operations', {
  bannerComment: '// Generated by scripts/gen-ops.mjs from spec/ops/*.schema.json. Do not edit.',
  additionalProperties: false,
  unreachableDefinitions: true,
  format: true,
  style: { singleQuote: true },
});
ts += '\n/** Each operation\'s request and response types, by operation name. */\nexport interface OpTypes {\n';
for (const [op, prefix] of ops) ts += `  '${op}': { request: ${prefix}Request; response: ${prefix}Response };\n`;
ts += '}\n\nexport type OpName = keyof OpTypes;\n';
fs.writeFileSync(out, ts);
console.log(`wrote ${path.relative(process.cwd(), out)} (${ops.length} operations)`);
